int ad2temperature(uint32_t adv) {
	int i;
	for(i=0;i<160;i++)
	if(adv >= ntcAdcENV[i])break;
	return i-30;
}

int ad2temperature2(uint32_t adv) {
	int a = 0;
	int b = 160;
	int c = (a + b) / 2;

	if(adv <= ntcAdcENV[b]) {
		return b - 30;
	} else if(adv >= ntcAdcENV[a]) {
		return a - 30;
	}

	do {
		if(ntcAdcENV[c] > adv) {//要找的温度在下半部
			a = c;
			c = (a + b) / 2;
		} else {  //要找的温度在上半部
			b = c;
			c = (a + b) / 2;
		}
	}while(b - a > 1);  // 0 1

	//a指向大数 低温。b指向小数 高温
	if(1){
		uint32_t ave = (ntcAdcENV[a] + ntcAdcENV[b]) / 2;
		if(adv > ave) {
			return a - 30;
		} else {
			return b - 30;
		}
	}
}

